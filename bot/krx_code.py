"""KRX 단축 종목코드 — 판정·정규화 단일 출처 (2026-11-10 그린광학 0015G0).

KRX 는 숫자 코드가 소진되자 신규 상장에 **영문 대문자가 섞인 6자리** 단축코드를
배정한다(그린광학 = `0015G0`, 2025-11 코스닥). 이 레포는 그 전까지 국내 코드를
두 방식으로만 다뤘고 둘 다 이 코드를 틀리게 읽는다:

- 숫자만 남기기(`"".join(ch for ch in c if ch.isdigit()).zfill(6)`) —
  `0015G0` → `00150` → `000150`(**두산**). 남의 회사 코드가 된다.
- `c.isdigit() and len(c) == 6` — 국내 코드가 아니라고 보고 KR 경로를 건너뛴다.

판정 기준: 숫자 6자리, 또는 **`0` 으로 시작하는** 영문 대문자·숫자 6자리.
`0` 으로 묶은 이유 — KRX **파생상품** 단축코드도 같은 꼴이다(ETF 구성종목의 코스피200
선물 `101V30`). 관측한 영문 혼합 **종목**코드(0015G0 · 0001A0)는 `0` 으로 시작하고
선물·옵션 코드는 `1`·`2`·`3` 으로 시작해 이 한 글자가 둘을 가른다. 6자 영문 심볼
(`ABCDEF`)·분기 표기(`2026Q3`)도 이 기준에서 빠진다. 근거는 관측까지이고 KRX 배정
규칙 원문은 재지 않았다(#165) — 규칙이 이 기준 밖의 코드를 내면 여기서 '' 가 된다.

⚠️ 못 보는 축(#274): 모양만으로는 **시장**을 정하지 못한다 — 대만 액티브 ETF
(`00981A`)가 같은 꼴이다. 접미 없는 코드를 KR 로 읽는 자리는 그 맥락(.KS/.KQ ·
보드의 시장 선언 · KRX 상장 목록 대조)이 따로 있어야 한다.
"""

from __future__ import annotations

import re

# 다른 정규식 안에 끼워 쓰는 원문(캡처 그룹 없음).
KRX_CODE_RE = r"(?:[0-9]{6}|0[0-9A-Z]{5})"
_FULL = re.compile(KRX_CODE_RE)
_JUNK = re.compile(r"[^0-9A-Za-z.]")


def is_krx_code(s) -> bool:
    """정확히 KRX 단축코드 모양인가(접미·공백·소문자는 받지 않는다)."""
    return isinstance(s, str) and _FULL.fullmatch(s) is not None


def krx_code(raw, *, pad: bool = True) -> str:
    """느슨한 입력 → KRX 단축코드, 못 만들면 ''.

    받는 것: 접미(`.KS`/`.KQ`/`.KN`), KRX 표기의 머리 `A`(`A005930`), 공백·괄호,
    소문자, 앞 0 이 빠진 정수(5930 → 005930). 숫자만 남기는 옛 정규화와 달리
    영문을 지우지 않으므로 0015G0 이 000150 이 되지 않는다.

    `pad=False` — 앞 0 을 채우지 않는다. 사람이 친 값(`/map`)은 5자리가 오타이지
    정수 저장의 흔적이 아니다(채우면 `12345` 가 남의 회사 `012345` 가 된다)."""
    s = _JUNK.sub("", "" if raw is None else str(raw)).upper().split(".")[0]
    if len(s) == 7 and s[0] == "A" and _FULL.fullmatch(s[1:]):
        s = s[1:]
    if pad and s.isdigit() and len(s) < 6:
        s = s.zfill(6)
    return s if _FULL.fullmatch(s) and s != "000000" else ""
