def _api_report_archive_send(file: str) -> dict:
    """GET /api/report_archive_send?file= — 저장된(이미 과금된) AI 보고서를 텔레그램
    채널로 전송(재과금 없음, 사용자 2026-06-18). GET(프록시 GET-only)·인증 뒤."""
    if not file:
        return {"ok": False, "error": "file 누락"}
    try:
        from trade.report_archive import send_to_channel
        return send_to_channel(file)
    except Exception as exc:
        log.warning("report_archive_send %s: %s", file, exc)
        return {"ok": False, "error": str(exc)}


def _api_report_archive_delete(file: str) -> dict:
    """GET /api/report_archive_delete?file= — AI 보고서 아카이브 카드 삭제 (사용자
    2026-06-18 휴지통). NOAH 프록시가 GET 만 포워드하므로 GET(인증·토큰 뒤라 안전).
    report_archive.delete 가 화이트리스트 정규식으로 path traversal 차단."""
    if not file:
        return {"ok": False, "error": "file 누락"}
    try:
        from trade.report_archive import delete
        return {"ok": bool(delete(file))}
    except Exception as exc:
        log.warning("report_archive_delete %s: %s", file, exc)
        return {"ok": False, "error": str(exc)}


def _api_company_report(q: str, mode: str, leaf: str = "") -> dict:
    """GET /api/company_report?q=&mode=free|llm&leaf= — 기업 중심 보고서 HTML (사용자
    2026-06-17 '버튼으로 보고서 뽑기, 무료+유료'). mode=llm 만 비용(opt-in). leaf=히트맵
    셀 클릭 품목명(breadcrumb, 2026-06-20). graceful."""
    if not q:
        return {"ok": False, "error": "회사명 또는 6자리 코드를 입력하세요."}
    try:
        if mode in ("channel", "channel_llm"):          # 텔레그램 채널 전송
            from trade.company_report import send_to_channel
            res = send_to_channel(q, "llm" if mode == "channel_llm" else "free")
            return {"ok": res.get("ok", False), "channel": True,
                    "sent": res.get("sent", 0), "error": res.get("error")}
        from trade.company_report import build
        html = build(q, "llm" if mode == "llm" else "free", leaf=leaf or None)
        return {"ok": True, "html": html, "mode": mode}
    except Exception as exc:
        log.warning("company_report api %s/%s: %s", q, mode, exc)
        return {"ok": False, "error": str(exc)}


