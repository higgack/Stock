# 정적 _MAP(대표주 수동)과 별개 라인으로 표기 — 출처 구분. ──────────────


def _store_db_path():
    import os
    from pathlib import Path
    return Path(os.environ.get("TRADE_DATA_DIR")
                or str(Path.home() / ".trade")) / "store.db"


def load_channel_pairs(db_path=None) -> list[tuple[str, list[str]]]:
    """store.db alerts → [(정규화 item 텍스트, 종목 리스트)] 1회 로드
    (매칭용 — 공백제거·소문자). DB 부재/실패 → [] (graceful)."""
    return [(item.replace(" ", "").lower(), toks)
            for item, toks in _load_alerts(db_path)]


def _clean_stocks(stocks, meta) -> list[str]:
    """alert stocks 토큰 정제 (순서 보존 dedupe) — 콤마 결합 분리('에코프로비엠,
    LG화학' → 둘), '관련종목 :' 머리말 제거, 14자 초과·다중공백(다사 결합) junk
    제외, 비상장 제외, 표준 표기 정규화(canon_company). 순수."""
    out: list[str] = []
    seen: set[str] = set()
    for s in stocks:
        if not isinstance(s, str):
            continue
        s = s.strip()
        if ":" in s:                      # '관련종목 : LG전자' 머리말 제거
            s = s.split(":")[-1].strip()
        parts = [p.strip() for p in s.split(",")] if "," in s else [s]
        for p in parts:
            if not p or len(p) > 14 or p.count(" ") >= 2:   # 다중공백=다사 junk
                continue
            if "비상장" in str(meta.get(p, "")):
                continue
            c = canon_company(p)
            k = c.replace(" ", "").lower()
            if k and k not in seen:
                seen.add(k)
                out.append(c)
    return out


def _load_alerts(db_path=None) -> list[tuple[str, list[str]]]:
    """store.db alerts → [(원본 item 텍스트, 종목 리스트)] 공용 로더.
    DB 부재/실패 → [] (graceful — 채널 라인만 생략). 비상장 메타 토큰
    제외 ('파미=비상장' 류 stocks_meta), 14자 초과 토큰 제외. 원본 item
    보존 — 매칭(load_channel_pairs)·미매칭 후보 표시(unmatched_candidates)
    공용."""
    import json as _json
    import sqlite3
    from pathlib import Path
    p = Path(db_path) if db_path else _store_db_path()
    if not p.exists():
        return []
    out: list[tuple[str, list[str]]] = []
    try:
        conn = sqlite3.connect(f"file:{p}?mode=ro", uri=True)
        try:
            cur = conn.execute("SELECT item, stocks, stocks_meta FROM alerts")
            for item, stocks_j, meta_j in cur.fetchall():
                if not item:
                    continue
                try:
                    stocks = _json.loads(stocks_j or "[]")
                    meta = _json.loads(meta_j or "{}")
                except Exception:
                    continue
                toks = _clean_stocks(stocks, meta)
                if toks:
                    out.append((str(item), toks))
        finally:
            conn.close()
    except Exception:
        return []
    return out


